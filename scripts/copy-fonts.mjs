// Copies the self-hosted OFL fonts from @fontsource into public/fonts and writes src/app/fonts.css.
// Self-hosting lets the 1080p PNG exporter embed exactly the same font files into the rasterised SVG.
import fs from 'node:fs';
import path from 'node:path';
const faces = [
  ['source-serif-4', 'Atlas Serif', [[400, 'normal'], [400, 'italic'], [600, 'normal'], [600, 'italic'], [700, 'normal']]],
  ['ibm-plex-sans-condensed', 'Atlas Sans', [[400, 'normal'], [400, 'italic'], [500, 'normal'], [600, 'normal'], [700, 'normal']]],
];
const subsets = { latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD', 'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF' };
let css = '/* Generated by scripts/copy-fonts.mjs — SIL Open Font License 1.1 (see public/fonts/OFL.txt) */\n';
const manifest = [];
for (const [pkg, family, variants] of faces) {
  for (const [w, s] of variants) for (const [sub, range] of Object.entries(subsets)) {
    const file = `${pkg}-${sub}-${w}-${s}.woff2`;
    const src = path.join('node_modules/@fontsource', pkg, 'files', file);
    if (!fs.existsSync(src)) continue;
    fs.copyFileSync(src, path.join('public/fonts', file));
    css += `@font-face{font-family:'${family}';font-style:${s};font-weight:${w};font-display:swap;src:url(/fonts/${file}) format('woff2');unicode-range:${range};}\n`;
    manifest.push({ family, weight: w, style: s, file: `/fonts/${file}`, unicodeRange: range });
  }
}
fs.copyFileSync('node_modules/@fontsource/source-serif-4/LICENSE', 'public/fonts/OFL.txt');
fs.writeFileSync('src/app/fonts.css', css);
fs.writeFileSync('public/fonts/manifest.json', JSON.stringify(manifest, null, 1));
console.log('fonts:', manifest.length);
