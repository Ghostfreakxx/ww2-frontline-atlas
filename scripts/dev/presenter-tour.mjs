// Dev helper: screenshot presenter panels at iPad sizes.
import { chromium } from 'playwright';
const [base, out, w = '1180', h = '820'] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, hasTouch: true });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto(`${base}/presenter`);
await p.waitForSelector('.conn.live');
await p.waitForTimeout(2500);
await p.locator('.scene-item', { hasText: 'Army Group Centre' }).click();
await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/tour-scene.png` });
await p.getByRole('tab', { name: 'Forces' }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/tour-forces.png` });
await p.locator('[aria-label^="Details for Army Group Centre"]').click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/tour-detail.png` });
await p.getByRole('tab', { name: 'Order of battle' }).click();
await p.locator('.oob-node', { hasText: 'Panzer Group 2' }).click();
await p.locator('.oob-node', { hasText: 'XXXXVII Motorised Corps' }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/tour-oob.png` });
await p.getByRole('tab', { name: 'History' }).click();
await p.screenshot({ path: `${out}/tour-history.png` });
await p.getByRole('tab', { name: 'Battles' }).click();
await p.screenshot({ path: `${out}/tour-battles.png` });
await p.getByRole('tab', { name: 'Layers' }).click();
await p.screenshot({ path: `${out}/tour-layers.png` });
await p.getByRole('tab', { name: 'Sources' }).click();
await p.screenshot({ path: `${out}/tour-sources.png` });
await p.getByRole('tab', { name: 'Episode' }).click();
await p.screenshot({ path: `${out}/tour-episode.png` });
await p.getByRole('button', { name: 'Display link and QR code' }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/tour-share.png` });
await b.close();
