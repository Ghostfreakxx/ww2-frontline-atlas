// Eastern Front 1941 — reconstructed frontline snapshots.
//
// Method. Each line is digitised north→south through anchor places whose capture/holding on or about the
// snapshot date is stated in the cited works (q:'a'). Vertices between anchors follow rivers or terrain and
// are interpolation (q:'b'). Where no continuous front existed (e.g. the Pripet Marshes in July 1941) the
// segment is marked q:'c' and drawn as a gap. These are atlas-style reconstructions for narration, not
// positions of units. The 22 June line is derived automatically from the 1941 border reconstruction.

const a = (lon: number, lat: number, place?: string, note?: string): FrontPoint => ({ at: [lon, lat], q: 'a', place, note });
const b = (lon: number, lat: number, note?: string): FrontPoint => ({ at: [lon, lat], q: 'b', note });
const c = (lon: number, lat: number, note?: string): FrontPoint => ({ at: [lon, lat], q: 'c', note });

